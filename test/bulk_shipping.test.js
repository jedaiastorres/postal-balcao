"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const ExcelJS=require("exceljs");
const bulk=require("../bulk_shipping");
function data(){
  return {
    pedido_referencia:"PEDIDO-EXEMPLO-1",
    remetente_nome:"Remetente Exemplo",remetente_cpf_cnpj:"12345678000199",
    remetente_telefone:"94988887777",remetente_cep:"68515000",
    remetente_logradouro:"Rua A",remetente_numero:"10",remetente_bairro:"Centro",
    remetente_cidade_uf:"Parauapebas/PA",
    destinatario_nome:"Cliente Exemplo",destinatario_cpf_cnpj:"12345678909",
    destinatario_telefone:"11988887777",destinatario_cep:"01001000",
    destinatario_logradouro:"Rua B",destinatario_numero:"50",
    destinatario_bairro:"Centro",destinatario_cidade_uf:"São Paulo/SP",
    peso_por_volume_kg:"1.5",comprimento_cm:"25",largura_cm:"25",altura_cm:"5",
    quantidade_volumes:"2",valor_declarado_total:"100.00",
    descricao_conteudo:"Brinde",quantidade_itens:"1",valor_unitario:"100.00",
    documento_tipo:"DCE",documento_chave:"1".repeat(20)+"99"+"1".repeat(22)
  };
}
test("model includes the exact expected 32 import headers",async()=>{
  const buf=await bulk.template();
  assert.ok(buf.length>1000);
  const wb=new ExcelJS.Workbook();
  await wb.xlsx.load(buf);
  const ws=wb.getWorksheet("Envios");
  assert.ok(ws);
  assert.deepEqual(bulk.HEADERS.map((_,i)=>String(ws.getRow(1).getCell(i+1).value)),bulk.HEADERS);
  assert.ok(wb.getWorksheet("Instrucoes"));
});
test("accepts filled XLSX and preserves DC-e plus real sender/destination CEPs",async()=>{
  const wb=new ExcelJS.Workbook();
  const ws=wb.addWorksheet("Envios");
  ws.addRow(bulk.HEADERS);
  const entry=data();ws.addRow(bulk.HEADERS.map(h=>entry[h]||""));
  const buf=await wb.xlsx.writeBuffer();
  const result=await bulk.parseUpload({name:"postagens.xlsx",contentBase64:Buffer.from(buf).toString("base64")});
  assert.equal(result.valid,1);
  assert.equal(result.invalid,0);
  assert.equal(result.rows[0].documentType,"DCE");
  assert.equal(result.rows[0].sender.cep,"68515000");
  assert.equal(result.rows[0].count,2);
});
test("rejects missing origin CEP, duplicate references, and mismatched fiscal models",()=>{
  const entry=data();
  assert.ok(bulk.validateRecord({...entry,remetente_cep:""},2).errors.some(x=>x.includes("CEP")));
  assert.ok(bulk.validateRecord({...entry,documento_tipo:"NFE"},2).errors.some(x=>x.includes("Chave")));
  const rows=[bulk.HEADERS,bulk.HEADERS.map(x=>entry[x]||""),bulk.HEADERS.map(x=>entry[x]||"")];
  assert.ok(bulk.validateTable(rows)[1].errors.some(x=>x.includes("repetida")));
});
test("accepts semicolon-separated CSV generated by Excel",async()=>{
  const entry=data();
  const content=bulk.HEADERS.join(";")+"\r\n"+bulk.HEADERS.map(x=>entry[x]||"").join(";")+"\r\n";
  const out=await bulk.parseUpload({name:"postagens.csv",contentBase64:Buffer.from(content,"utf8").toString("base64")});
  assert.equal(out.valid,1);
  assert.equal(out.rows[0].items[0].description,"Brinde");
});
